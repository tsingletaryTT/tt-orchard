"""Is a model server decoding as fast as it did when it was healthy?

The watcher asks a server for one fixed greedy answer and divides the tokens the server says it generated by the
seconds the request took. It compares that with the best speed seen before for the same model at the same endpoint.
Three samples in a row below half of that best speed make the verdict `slow`. A slow server is reported, never
restarted: a restart interrupts every client of the server, so it is a person's decision.

Why not read the server log. vLLM's "Avg generation throughput" is tokens over the whole 10 s window. An agent's turns
are short tool calls with idle time between them, so a healthy server reads 5 to 8 tok/s there (measured idle at
38.7 tok/s the same hour, 2026-10-17). A request the client times itself has no such window.

What it does not know: whether a low number comes from the server (a stuck state, a hot or throttled chip), from other
clients sharing it (two clients measured 77% each, three 60%), or from a baseline that no longer applies because the
server was changed on purpose. The verdict says all three, and `reset` forgets a baseline.
"""
from __future__ import annotations

import http.client
import json
import math
import re
import time
import urllib.request
from dataclasses import dataclass, replace
from pathlib import Path

from orchard import safeio
from orchard.canary import CanaryError, post_json
from orchard.defaults import (SPEED_BASELINE_FILE, SPEED_MAX_TOKENS, SPEED_MIN_TOKENS, SPEED_PROMPT,
                              SPEED_SLOW_CONSECUTIVE, SPEED_SLOW_RATIO, SPEED_TIMEOUT_S)

MAX_TOKENS, MIN_TOKENS, PROMPT = SPEED_MAX_TOKENS, SPEED_MIN_TOKENS, SPEED_PROMPT
TIMEOUT_S, SLOW_RATIO, SLOW_CONSECUTIVE = SPEED_TIMEOUT_S, SPEED_SLOW_RATIO, SPEED_SLOW_CONSECUTIVE
METRICS_TIMEOUT_S = 3.0    # choice: /metrics answers at once on a live server; a server that does not is not asked twice


class SpeedError(Exception):
    """The server gave no answer that can be timed."""


@dataclass(frozen=True)
class Sample:
    tok_s: float
    tokens: int
    seconds: float
    others: int | None = None     # requests of other clients running on the server during this one; None: not known


@dataclass(frozen=True)
class Verdict:
    state: str                  # unknown (no baseline), ok, suspect (low, but not for long enough), slow,
                                # busy (another client's request was running: the sample says nothing)
    tok_s: float                # the newest sample
    baseline: float | None
    ratio: float | None         # newest sample over the baseline
    message: str


@dataclass(frozen=True)
class Check:
    sample: Sample
    verdict: Verdict


def _base_url(endpoint: str) -> str:
    """The chat URL for an endpoint written with or without its /v1 (the tiers write both forms)."""
    base = endpoint.rstrip("/")
    if not base.endswith("/v1"):
        base += "/v1"
    return base + "/chat/completions"


def _origin(endpoint: str) -> str:
    base = endpoint.rstrip("/")
    return base[:-3] if base.endswith("/v1") else base


def _get_text(url: str, timeout: float) -> str:
    with urllib.request.urlopen(url, timeout=timeout) as resp:
        return resp.read().decode("utf-8", errors="replace")


GAUGE_RE = re.compile(r"^vllm:num_requests_running\{[^}]*\}\s+([0-9.eE+-]+)\s*$", re.MULTILINE)


def running_requests(endpoint: str, *, get=_get_text) -> int | None:
    """How many requests the server is running now, from vLLM's /metrics (`vllm:num_requests_running`, added over the
    engines), or None when the server does not say (another kind of server, no answer, an odd value)."""
    try:
        text = get(_origin(endpoint) + "/metrics", METRICS_TIMEOUT_S)
        values = [float(v) for v in GAUGE_RE.findall(text)]
    except (OSError, ValueError, http.client.HTTPException):          # a reply cut off mid-body is not an OSError
        return None
    return int(sum(values)) if values else None


def measure(endpoint: str, model: str, *, post=post_json, clock=time.monotonic, timeout: float = TIMEOUT_S,
            running=None) -> Sample:
    """One fixed greedy answer, timed by the client."""
    url = _base_url(endpoint)
    body = {"model": model, "messages": [{"role": "user", "content": PROMPT}], "temperature": 0,
            "max_tokens": MAX_TOKENS, "stream": False, "chat_template_kwargs": {"enable_thinking": False}}
    running = running or running_requests
    before = running(endpoint)
    start = clock()
    try:
        data = post(url, body, timeout)
    except (OSError, ValueError, CanaryError, http.client.HTTPException) as exc:   # IncompleteRead and BadStatusLine are not OSError
        raise SpeedError(f"the speed request to {url} failed: {exc}") from exc
    seconds = clock() - start
    after = running(endpoint)
    seen = [n for n in (before, after) if n is not None]
    others = max(seen) if seen else None
    usage = data.get("usage") if isinstance(data, dict) else None
    tokens = usage.get("completion_tokens") if isinstance(usage, dict) else None
    if isinstance(tokens, bool) or not isinstance(tokens, int):
        raise SpeedError(f"{url} did not say how many tokens it generated (usage.completion_tokens)")
    if seconds <= 0:
        raise SpeedError(f"{url}: the request took no measurable time")
    if tokens < MIN_TOKENS:
        raise SpeedError(f"{url} answered with only {tokens} tokens, too few to time (need {MIN_TOKENS})")
    return Sample(tok_s=tokens / seconds, tokens=tokens, seconds=seconds, others=others)


def judge(samples: list[float], baseline: float | None, *, ratio: float = SLOW_RATIO,
          consecutive: int = SLOW_CONSECUTIVE) -> Verdict:
    """The state from the samples so far (oldest first), against the best speed seen."""
    if not samples:
        raise ValueError("judge needs at least one sample")
    now = samples[-1]
    if baseline is not None and not (math.isfinite(baseline) and baseline > 0):
        raise ValueError(f"the baseline must be a speed greater than 0 tok/s, not {baseline!r}")
    if baseline is None:
        return Verdict("unknown", now, None, None,
                       f"{now:.1f} tok/s; there is no baseline for this server yet, so this sample becomes the baseline.")
    floor = baseline * ratio
    r = now / baseline
    recent = samples[-consecutive:]
    if len(recent) == consecutive and all(s < floor for s in recent):
        return Verdict(
            "slow", now, baseline, r,
            f"SLOW: {now:.1f} tok/s, {r:.0%} of the best seen ({baseline:.1f} tok/s), and the last {consecutive} samples "
            f"were all below {ratio:.0%}. This server may need a restart; that is a person's decision, because a restart "
            "interrupts everything using it. Other clients on the server lower this number (two clients measured "
            "about 77% each, three about 60%). If the server was changed on purpose (another profile or model build), "
            "run again with --reset-baseline.")
    if now < floor:
        return Verdict("suspect", now, baseline, r,
                       f"{now:.1f} tok/s is {r:.0%} of the best seen ({baseline:.1f} tok/s); one low sample, "
                       f"{consecutive} in a row make it slow.")
    return Verdict("ok", now, baseline, r, f"{now:.1f} tok/s, {r:.0%} of the best seen ({baseline:.1f} tok/s).")


MAX_BASELINE_BYTES = 1 << 20            # one small entry per model and endpoint; a larger file is not one


class Baselines:
    """The best decode speed seen per model and endpoint, in a small JSON file. It only goes up: a slow sample never
    lowers it, so a server that has gone slow is still compared with its healthy speed."""

    def __init__(self, path):
        self.path = Path(path)

    @staticmethod
    def key(endpoint: str, model: str) -> str:
        return f"{endpoint.rstrip('/')} {model}"

    def _read(self) -> dict:
        try:
            data = safeio.read_json(self.path, max_bytes=MAX_BASELINE_BYTES, expect=dict)
        except safeio.SafeReadError:
            return {}                          # missing, hostile (a FIFO, a link, a huge or deeply nested file, NaN) or not an object
        return {k: v for k, v in data.items() if isinstance(v, dict) and isinstance(v.get("tok_s"), (int, float))
                and not isinstance(v["tok_s"], bool) and v["tok_s"] > 0}

    def _write(self, data: dict) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        safeio.atomic_write(self.path, json.dumps(data, indent=2, sort_keys=True) + "\n", mode=0o644)

    def get(self, endpoint: str, model: str) -> float | None:
        entry = self._read().get(self.key(endpoint, model))
        return float(entry["tok_s"]) if entry else None

    def update(self, endpoint: str, model: str, tok_s: float) -> float:
        """Keep the larger of the stored speed and `tok_s`; return what is stored now."""
        data, k = self._read(), self.key(endpoint, model)
        best = max(tok_s, data[k]["tok_s"]) if k in data else tok_s
        if k not in data or best > data[k]["tok_s"]:
            data[k] = {"tok_s": best, "at": time.strftime("%Y-%m-%dT%H:%M:%S%z")}
            self._write(data)
        return best

    def reset(self, endpoint: str, model: str) -> None:
        data = self._read()
        if data.pop(self.key(endpoint, model), None) is not None:
            self._write(data)


def check(endpoint: str, model: str, store: Baselines, *, history: list, baseline: float | None = None,
          post=post_json, clock=time.monotonic, running=None) -> Check:
    """Measure once, judge against the baseline (a given `baseline` wins and is not stored), learn, and append the
    sample to `history`. The baseline is judged before it is raised, so a fast sample cannot hide a slow trend.

    A sample taken while another client's request was running is `busy`: it is not appended to `history`, does not
    count towards slow and does not touch the baseline. A decode step serves every running request, so one long
    conversation in the batch slows all of them (2026-10-17: 7.3 tok/s for a fresh request beside an agent's long
    conversation, 38.7 on the idle server). When the server does not report its running requests, the sample counts
    and a slow or suspect verdict says it could not tell."""
    sample = measure(endpoint, model, post=post, clock=clock, running=running)
    stored = store.get(endpoint, model)
    base = baseline if baseline is not None else stored
    if sample.others:
        n = sample.others
        return Check(sample, Verdict(
            "busy", sample.tok_s, base, None if base is None else sample.tok_s / base,
            f"{n} other request{'s were' if n != 1 else ' was'} running on the server, so this {sample.tok_s:.1f} tok/s "
            "sample does not say whether the server is slow (a long conversation in the batch slows every request)."))
    history.append(sample.tok_s)
    verdict = judge(history, base)
    if sample.others is None and verdict.state in ("slow", "suspect"):
        verdict = replace(verdict, message=verdict.message + " (The server did not report its running requests, so I "
                          "could not tell whether other requests were running; another client may be why.)")
    if baseline is None:
        store.update(endpoint, model, sample.tok_s)
    return Check(sample, verdict)


CONFIRM_INTERVAL_S = 10.0    # choice: between the re-checks of a low sample; a sample takes about 8 s on a healthy server


def confirm(endpoint: str, model: str, store: Baselines, *, history: list, baseline: float | None = None,
            interval: float = CONFIRM_INTERVAL_S, post=post_json, clock=time.monotonic, sleep=time.sleep,
            running=None) -> Check:
    """`check`, and while the verdict is only `suspect`, up to SLOW_CONSECUTIVE - 1 more samples, so a single busy
    moment is not reported as slow and three low samples in a row are, within about half a minute. Stops at the first
    sample that is not low. A request that fails raises SpeedError."""
    result = check(endpoint, model, store, history=history, baseline=baseline, post=post, clock=clock, running=running)
    for _ in range(SLOW_CONSECUTIVE - 1):
        if result.verdict.state != "suspect":
            break
        sleep(interval)
        result = check(endpoint, model, store, history=history, baseline=baseline, post=post, clock=clock,
                       running=running)
    return result


def probe_check(home, *, post=post_json, clock=time.monotonic, sleep=time.sleep, running=None):
    """The speed check the kernel probe runs before each attempt: a function (endpoint, model) -> dict, which keeps one
    history per server across the calls. The dict is what the attempt's record holds: state, tok_s, baseline, ratio and
    message. A server that cannot be measured gives state `error`, which never stops a probe (the attempt then shows
    what the coder does)."""
    store = Baselines(Path(home) / ".cache" / "tt-orchard" / SPEED_BASELINE_FILE)
    histories: dict[str, list] = {}

    def run_check(endpoint: str, model: str) -> dict:
        history = histories.setdefault(Baselines.key(endpoint, model), [])
        try:
            c = confirm(endpoint, model, store, history=history, post=post, clock=clock, sleep=sleep, running=running)
        except SpeedError as exc:
            return {"state": "error", "tok_s": None, "baseline": None, "ratio": None, "message": str(exc)}
        v = c.verdict
        return {"state": v.state, "tok_s": round(c.sample.tok_s, 1),
                "baseline": None if v.baseline is None else round(v.baseline, 1),
                "ratio": None if v.ratio is None else round(v.ratio, 3), "message": v.message}
    return run_check


# ---- the command: tt-orchard coder-speed ---------------------------------------------------------------------------

EXIT_OK, EXIT_ERROR, EXIT_SLOW = 0, 2, 3
ERRORS_IN_A_ROW = 3          # in --watch, this many failed requests in a row end the watch (exit 2)
DEFAULT_INTERVAL_S = 20.0    # choice: between the samples of one run; a sample takes about 8 s on a healthy server


def _targets(args, tier_config) -> tuple[list[dict], str | None]:
    """([{label, endpoint, model}], an error text). Each distinct server (endpoint without a trailing slash, and model)
    appears once, with the names of every tier that uses it."""
    if args.endpoint and args.model and not args.tiers:
        return [{"label": "server", "endpoint": args.endpoint, "model": args.model}], None
    if args.endpoint or args.model:
        if not args.tiers:
            return [], "--endpoint and --model go together; pass both, or neither to use the tier config"
    if tier_config is None:
        return [], ("no server is known: pass --endpoint URL and --model NAME, or keep a bringup.toml whose tier config "
                    "names the coder (--tiers checks every tier in it)")
    if args.tiers:
        names = sorted(tier_config.tiers)
    else:
        from orchard.kernelprobe import CODER_STAGE
        from orchard.stages import tier_for
        names = [tier_for(tier_config, CODER_STAGE, phase="main", escalated=False)]
    found: dict[tuple, dict] = {}
    for name in names:
        t = tier_config.tiers[name]
        k = (t["endpoint"].rstrip("/"), t["model"])
        if k in found:
            found[k]["label"] += f"+{name}"
        else:
            found[k] = {"label": name, "endpoint": t["endpoint"], "model": t["model"]}
    return list(found.values()), None


def _line(t: dict, v: Verdict) -> str:
    return f"{t['label']:<8} {t['endpoint']}  {t['model']}: [{v.state}] {v.message}"


def run(args, *, out, home, tier_config=None, post=post_json, clock=time.monotonic, sleep=time.sleep,
        running=None) -> int:
    """Measure each server; exit 0 (ok, suspect or no baseline yet), 2 (a server could not be measured) or 3 (slow)."""
    targets, error = _targets(args, tier_config)
    if error:
        print(f"error: {error}", file=out)
        return EXIT_ERROR
    if args.baseline is not None and not (math.isfinite(args.baseline) and args.baseline > 0):
        print(f"error: --baseline must be a speed greater than 0 tok/s, not {args.baseline!r}", file=out)
        return EXIT_ERROR
    store = Baselines(args.baseline_file or Path(home) / ".cache" / "tt-orchard" / SPEED_BASELINE_FILE)
    if args.reset_baseline:
        for t in targets:
            store.reset(t["endpoint"], t["model"])
    watching = args.watch is not None
    interval = args.watch if watching else args.interval
    history = {id(t): [] for t in targets}
    results: dict[int, tuple[Verdict | None, str | None]] = {id(t): (None, None) for t in targets}
    errors_in_a_row, n = 0, 0
    try:
        while True:
            n += 1
            round_failed = False
            for t in targets:
                try:
                    c = check(t["endpoint"], t["model"], store, history=history[id(t)], baseline=args.baseline,
                              post=post, clock=clock, running=running)
                except SpeedError as exc:
                    results[id(t)] = (None, str(exc))
                    round_failed = True
                    if not args.json:
                        print(f"{t['label']:<8} {t['endpoint']}  {t['model']}: error: {exc}", file=out)
                    continue
                results[id(t)] = (c.verdict, None)
                if not args.json and (watching or n == (args.samples or 1)):
                    print(_line(t, c.verdict), file=out)
            errors_in_a_row = errors_in_a_row + 1 if round_failed else 0
            any_slow = any(v and v.state == "slow" for v, _ in results.values())
            if watching:
                if any_slow:
                    break
                if errors_in_a_row >= ERRORS_IN_A_ROW:
                    print(f"error: {ERRORS_IN_A_ROW} errors in a row; the watch ends", file=out)
                    break
                sleep(interval)
                continue
            if n >= (args.samples or 1) or round_failed:
                break
            sleep(interval)
    except KeyboardInterrupt:
        print("stopped", file=out)
        return EXIT_OK
    if args.json:
        rows = []
        for t in targets:
            v, err = results[id(t)]
            rows.append({"label": t["label"], "endpoint": t["endpoint"], "model": t["model"],
                         "state": v.state if v else "error", "tok_s": v.tok_s if v else None,
                         "baseline": v.baseline if v else None, "ratio": v.ratio if v else None,
                         "message": v.message if v else err})
        print(json.dumps(rows, indent=2), file=out)
    if any(err for _, err in results.values()) and not any_slow:
        return EXIT_ERROR
    return EXIT_SLOW if any_slow else EXIT_OK
