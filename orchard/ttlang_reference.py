"""The coder's reference files, taken from the tt-lang the simulator runs.

The kernel probe puts five files in each attempt's reference/ directory: guide.md, examples.md, the specification and
two example kernels. The specification and the examples always come from the tt-lang checkout at the pinned commit
(orchard/ttlang_pin.py). The guide and the examples.md index used to come from the installed tt-lang skill, which
documents an older specification (0.12 against the checkout's 0.20 when this module was written). A coder taught
`ttl.kernel` and then run against a simulator that only knows `ttl.operation` is tested on a language it was not taught.

`assemble` closes that gap:

  * the skill's guide.md and examples.md are shipped only when the specification version the skill documents equals the
    checkout's;
  * when the versions differ, both files are generated from the checkout's own docs (GUIDE_DOCS, EXAMPLES_DOCS), into
    memory, and the probe writes them into the run's own reference directory;
  * when either version cannot be read, the skill's files are kept (nothing says they differ) and the record says the
    version is unknown.

Threat model. The checkout is operator-owned and the harness installs it at the pin (`tt-orchard kernel-env`). The
defenses here cover an accidental edit, an untracked file left in it, and a checkout that has configured git or contains
links or very large files: nothing in it is run, and nothing in it is read, unless the pinned commit has it unchanged;
verify() (ttlang_env.py) runs pinned copies in a directory made for the call with a minimal environment. They do not claim
to defend against someone who can already write to the operator's files, who has easier ways to the same end.

Each file carries its source, sha256, the specification version it documents (None when unknown) and whether it was
generated. Nothing is written into the checkout, the skill directory or the venv. Files are read through
ttlang_env._read_reference, which refuses links, devices and oversized files.
"""
from __future__ import annotations

import hashlib
import os
import stat
from pathlib import Path

from orchard import ttlang_env, ttlang_pin

# The checkout's docs a generated guide.md is made of, in reading order (paths under the checkout).
GUIDE_DOCS = (
    "docs/sphinx/overview.md",
    "docs/sphinx/programming-guide.md",
    "docs/sphinx/simulator-getting-started.md",
    "docs/sphinx/simulator.md",
)
# What a generated examples.md is made of.
EXAMPLES_DOCS = ("docs/EXAMPLES.md", "examples/README.md")
SPEC_REL = "docs/sphinx/specs/TTLangSpecification.md"


def _version_of(path: Path) -> str | None:
    from orchard import skillsfresh
    data = skillsfresh._read_regular(path)
    return skillsfresh.spec_version(data) if data else None


def checkout_spec_version(src_dir) -> str | None:
    """The specification version the tt-lang checkout documents, read from its own TTLangSpecification.md."""
    return _version_of(Path(src_dir) / SPEC_REL)


def skill_spec_version(skill_dir) -> str | None:
    """The specification version the installed tt-lang skill documents."""
    return _version_of(Path(skill_dir) / "TTLangSpecification.md")


def _generate(name: str, docs: tuple[str, ...], env, skill_ver, src_ver, problems: list[str]) -> dict | None:
    """One generated reference file: a header that says what it is, then each source doc under its own marker."""
    src = Path(env.src_dir)
    parts, used = [], []
    for rel in docs:
        data, why = ttlang_env._read_reference(src / rel, src)
        if why:
            problems.append(why)
            continue
        used.append(rel)
        parts.append(f"\n\n<!-- source: {rel} -->\n\n".encode() + data)
    if len(used) != len(docs):
        return None
    head_sha = ttlang_env.head_sha(env) or "an unknown commit"
    header = (f"<!-- generated by tt-orchard from the tt-lang checkout at {head_sha}, which documents specification "
              f"{src_ver}. The installed tt-lang skill documents {skill_ver or 'an unknown version'}, so its {name} is "
              f"not used (skill documents {skill_ver or 'unknown'}). Sources: {', '.join(used)}. -->").encode()
    data = header + b"".join(parts)
    if len(data) > ttlang_env.REFERENCE_MAX_BYTES:
        problems.append(f"the generated {name} is larger than {ttlang_env.REFERENCE_MAX_BYTES // 1024} KiB")
        return None
    return {"name": name, "source": ttlang_env.CHECKOUT_SOURCE, "path": f"generated from {', '.join(used)} in {src}",
            "sha256": hashlib.sha256(data).hexdigest(), "data": data, "spec_version": src_ver, "generated": True,
            "generated_from": used}


REFERENCE_SOURCES = ("checkout", "skill")


def assemble(env, skill_dir, reference_source: str = "checkout") -> tuple[list[dict], list[str]]:
    """(files, problems), in the order of ttlang_env.REFERENCES. Each file is {"name", "source", "path", "sha256",
    "data", "spec_version", "generated"} and, when generated, "generated_from".

    `reference_source` is "checkout" (the default: the pinned set described above) or "skill": the set as it was before the pin,
    which is the installed skill's guide.md and examples.md whatever version they document, the checkout's specification
    and the two fixed example kernels, and none of the extra example kernels. "skill" exists to measure whether the pinned
    set helps the coder (docs/run-logs/2026-10-29-pinned-reference-ab.md)."""
    if reference_source not in REFERENCE_SOURCES:
        raise ValueError(f"unknown reference source {reference_source!r}; the sources are {', '.join(REFERENCE_SOURCES)}")
    skill_dir = Path(skill_dir)
    skill_ver, src_ver = skill_spec_version(skill_dir), checkout_spec_version(env.src_dir)
    use_checkout = reference_source == "checkout" and bool(skill_ver and src_ver and skill_ver != src_ver)
    roots = {ttlang_env.SKILL_SOURCE: skill_dir, ttlang_env.CHECKOUT_SOURCE: Path(env.src_dir)}
    files, problems = [], []
    generated = {"guide.md": GUIDE_DOCS, "examples.md": EXAMPLES_DOCS}
    for name, source, rel in ttlang_env.REFERENCES:
        if use_checkout and name in generated:
            g = _generate(name, generated[name], env, skill_ver, src_ver, problems)
            if g:
                files.append(g)
            continue
        path = roots[source] / rel
        data, why = ttlang_env._read_reference(path, roots[source])
        if why:
            problems.append(why)
            continue
        files.append({"name": name, "source": source, "path": str(path), "sha256": hashlib.sha256(data).hexdigest(),
                      "data": data, "spec_version": skill_ver if source == ttlang_env.SKILL_SOURCE else src_ver,
                      "generated": False})
    src = Path(env.src_dir)
    tracked, dirty = git_state(env)
    extras, why = extra_examples(src, {n for n, _, _ in ttlang_env.REFERENCES}, tracked) if reference_source == "checkout" else ([], None)
    if why:
        problems.append(why)
    for name in extras:
        path = src / "examples" / name
        data, why = ttlang_env._read_reference(path, src)
        if why:
            problems.append(why)
            continue
        files.append({"name": name, "source": ttlang_env.CHECKOUT_SOURCE, "path": str(path),
                      "sha256": hashlib.sha256(data).hexdigest(), "data": data, "spec_version": src_ver,
                      "generated": False})
    # Every file taken from the checkout must be the file the pinned commit has: a modified or untracked one is refused.
    for where in sorted(k for k, v in (dirty or {}).items() if v == "link"):
        problems.append(f"{'the checkout root' if where == '.' else where} in {env.src_dir} is a link; the reference "
                        "files must not be reached through a linked directory")
    if dirty:
        taken = [r for _, source, r in ttlang_env.REFERENCES if source == ttlang_env.CHECKOUT_SOURCE]
        taken += [f"examples/{n}" for n in extras] + [SPEC_REL]
        if use_checkout:
            taken += list(GUIDE_DOCS) + list(EXAMPLES_DOCS)
        for rel in dict.fromkeys(taken):
            if dirty.get(rel) not in (None, "deleted"):
                problems.append(f"{rel} is {dirty[rel]} in the checkout {env.src_dir}; the reference files are taken "
                                "only from files the pinned commit has, unchanged")
    return files, problems


# Every git call we make on the checkout is one that reads objects and nothing else: `ls-tree` and `cat-file blob`. Neither
# applies a clean or smudge filter, a textconv or diff driver, or the index's file-system monitor, and neither runs a hook.
# `git status` and `git diff` do (they hash the working tree through the checkout's own attributes and config), so they are
# never used: modified and untracked files are found in Python (git_state). The settings below are a second layer, for the
# day someone adds a call; a test fails on any argument list that lacks them or names status, diff or show.
GIT_SAFE_CONFIG = ("-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null", "-c", "core.attributesFile=/dev/null",
                   "-c", "core.useReplaceRefs=false")      # a refs/replace entry must not redirect the pinned commit
# Limits of the working-tree scan: a file above FILE_CAP is not opened (reported "unchecked"), the files hashed together stop at
# TOTAL_CAP, a walk stops at MAX_ENTRIES. Files are hashed CHUNK bytes at a time.
FILE_CAP = 4 * 1024 * 1024         # choice: four times the largest file given to the coder (REFERENCE_MAX_BYTES, 1 MiB)
TOTAL_CAP = 64 * 1024 * 1024       # choice: the checkout's examples/ and docs/ are about 37 MB at the pin; most of it is not compared
MAX_ENTRIES = 20000                # choice: the checkout has about 180 files there
CHUNK = 1024 * 1024
WORKTREE_DIRS = ("examples", "docs")
IGNORED_DIRS = ("__pycache__", ".git")         # what running an example leaves behind; a file in one is never offered


def git_env(env) -> dict:
    """The environment of a git call on the checkout: the allow-listed one, no system or user config, no system
    attributes, and no index refresh."""
    out = ttlang_env.minimal_env(env)
    out.update({"GIT_OPTIONAL_LOCKS": "0", "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null",
                "GIT_ATTR_NOSYSTEM": "1", "GIT_NO_REPLACE_OBJECTS": "1"})
    # The same safe settings as environment config, so a call that cannot take `-c` arguments (and a fake that matches on
    # the argument list) still gets them. The operator's own GIT_DIR, GIT_WORK_TREE and the like are not inherited.
    pairs = [(GIT_SAFE_CONFIG[i + 1].split("=", 1)) for i in range(0, len(GIT_SAFE_CONFIG), 2)]
    out["GIT_CONFIG_COUNT"] = str(len(pairs))
    for n, (key, value) in enumerate(pairs):
        out[f"GIT_CONFIG_KEY_{n}"], out[f"GIT_CONFIG_VALUE_{n}"] = key, value
    return out


def git_argv(env, *args: str) -> list[str]:
    """`git -C <checkout> <safe settings> <args>`."""
    return ["git", "-C", str(env.src_dir), *GIT_SAFE_CONFIG, *args]


def _blob_id(path: Path, size_cap: int) -> tuple[str | None, str]:
    """(git blob id, "ok") of a file or link in the working tree, computed here with no git and no filter. The file is
    opened without following a link, its size is taken from the open descriptor, and a file above `size_cap` is not read:
    (None, "unchecked"). The bytes are hashed CHUNK at a time after the blob header, so no file is held whole. An entry that
    cannot be read, is not a file or link, or changes while it is read gives (None, "unreadable")."""
    try:
        st = os.lstat(path)
        if stat.S_ISLNK(st.st_mode):
            data = os.fsencode(os.readlink(path))
            return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest(), "ok"
        if not stat.S_ISREG(st.st_mode):
            return None, "unreadable"
        if st.st_size > size_cap:
            return None, "unchecked"
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0))
        with os.fdopen(fd, "rb") as f:
            fst = os.fstat(f.fileno())
            if not stat.S_ISREG(fst.st_mode):
                return None, "unreadable"
            if fst.st_size > size_cap:
                return None, "unchecked"
            h = hashlib.sha1(b"blob %d\0" % fst.st_size)
            seen = 0
            while True:
                chunk = f.read(CHUNK)
                if not chunk:
                    break
                seen += len(chunk)
                if seen > fst.st_size:
                    return None, "unreadable"       # it grew while it was read
                h.update(chunk)
            if seen != fst.st_size:
                return None, "unreadable"           # it shrank while it was read
            return h.hexdigest(), "ok"
    except OSError:
        return None, "unreadable"


def _walk(root: Path, top: str):
    """(relative path, absolute path) of every file and link under root/top, and a list of the directories that
    could not be listed. Links to directories are entries, never entered; `top` itself must not be a link (the caller
    checks). At most MAX_ENTRIES are returned, and the last item says whether the walk was cut."""
    found, errors, cut = [], [], False

    def onerror(exc):
        if not isinstance(exc, FileNotFoundError):          # an absent directory has no files; anything else is reported
            errors.append(f"{top}: {exc.strerror or exc}")
    for base, dirs, files in os.walk(root / top, followlinks=False, onerror=onerror):
        dirs[:] = sorted(d for d in dirs if d not in IGNORED_DIRS and not os.path.islink(os.path.join(base, d)))
        try:
            links = [d for d in os.listdir(base) if os.path.islink(os.path.join(base, d))
                     and os.path.isdir(os.path.join(base, d))]
        except OSError:
            links = []
        for name in sorted(list(files) + links):
            if name.endswith(".pyc"):
                continue
            if name == ".git" and Path(base) == root / top and top == ".":
                continue                # a linked worktree's metadata is a .git file at the root; git never tracks it (issue 202)
            if len(found) >= MAX_ENTRIES:
                return found, errors, True
            absolute = Path(base) / name
            found.append((absolute.relative_to(root).as_posix(), absolute))
    return found, errors, cut


def _state(env, allow_head: bool = False):
    """(rev, {path: blob id} at that commit, {path: "modified"|"untracked"|"deleted"} in the working tree), each None
    when it cannot be known. The commit is the pinned one; with `allow_head` and no pinned commit in the checkout, HEAD."""
    tracked, rev = None, ttlang_pin.SHA
    for candidate in [ttlang_pin.SHA] + (["HEAD"] if allow_head else []):
        rc, out, _ = env.run(git_argv(env, "ls-tree", "-r", "-z", candidate, "--", *WORKTREE_DIRS), 60, git_env(env))
        if rc == 0:
            tracked, rev = parse_tree(out), candidate
            break
    if tracked is None:
        return rev, None, None
    return rev, tracked, scan_tree(Path(env.src_dir), WORKTREE_DIRS, tracked)


def parse_tree(out: str) -> dict[str, str]:
    """{path: blob id} from `git ls-tree -r -z` output. A submodule entry is not a file and is left out."""
    tracked = {}
    for record in out.split("\0"):
        meta, _, path = record.partition("\t")
        parts = meta.split()
        if path and len(parts) == 3 and parts[1] == "blob":
            tracked[path] = parts[2]
    return tracked


def scan_tree(root: Path, tops, tracked: dict[str, str]) -> dict[str, str]:
    """{path: "modified"|"untracked"|"deleted"|"unchecked"|"unreadable"|"link"|"too many"} for the working tree under
    root/top for each top ("." is the whole checkout, `.git` excluded), compared with `tracked`, read only, with no git. See
    git_state for the meaning of each word."""
    dirty = {}
    seen, hashed, skipped = set(), 0, set()
    if os.path.islink(root):                    # a linked checkout is not walked, hashed or run
        return {".": "link"}
    for top in tops:
        if os.path.islink(root / top):          # os.walk would follow the starting directory
            dirty[top] = "link"
            skipped.add(top)
            continue
        files, errors, cut = _walk(root, top)
        if cut:
            dirty["(entries)"] = "too many"
        for rel, absolute in files:
            seen.add(rel)
            if rel not in tracked:
                dirty[rel] = "untracked"
                continue
            size = 0
            try:
                size = os.lstat(absolute).st_size
            except OSError:
                pass
            if hashed + size > TOTAL_CAP:
                dirty[rel] = "unchecked"
                continue
            blob, how = _blob_id(absolute, FILE_CAP)
            if how == "ok":
                hashed += size
                if blob != tracked[rel]:
                    dirty[rel] = "modified"
            else:
                dirty[rel] = how
        for why in errors:
            dirty[why] = "unreadable"
    for rel in tracked:
        if rel not in seen and (tops == (".",) or rel.split("/", 1)[0] in tops and rel.split("/", 1)[0] not in skipped):
            dirty[rel] = "deleted"
    return dirty


def git_state(env, allow_head: bool = False) -> tuple[set[str] | None, dict[str, str] | None]:
    """(tracked, dirty) for the checkout's examples/ and docs/, read only and with no filter run. `tracked` is the set of
    paths the pinned commit has there; `dirty` maps each path whose working-tree bytes differ from the commit's
    ("modified"), that the commit does not have ("untracked") or that is missing ("deleted"); a file that was not compared
    because it is above FILE_CAP or past TOTAL_CAP ("unchecked"); a file or directory that could not be read
    ("unreadable"); examples/, docs/ or the checkout itself being a link ("link"); and "(entries)" when the walk was cut.
    Only "unchecked" is not a difference. Both are None when git cannot answer (no git, the pinned commit is not in the
    checkout): the caller then does not trust the checkout's extra files, and the consistency check says it could not
    tell. File modes are not compared."""
    _, tracked, dirty = _state(env, allow_head)
    return (set(tracked) if tracked is not None else None), dirty


# The checkout's own example programs that show the patterns the failing kernels need (element-wise work, broadcast and
# reduce) go in as full files beside the two fixed examples. A name matches when it holds one of these words.
EXTRA_EXAMPLE_WORDS = ("eltwise", "broadcast", "reduce")
EXTRA_EXAMPLE_SKIP = ("multidevice",)   # all-reduce across devices is not a single-chip kernel pattern
EXTRA_EXAMPLE_MAX = 8       # choice: the checkout has five such files at the pin; the cap keeps a new checkout bounded


def _is_file_entry(entry) -> bool:
    try:
        return not entry.is_dir(follow_symlinks=False)
    except OSError:                          # an entry that cannot be examined is not offered
        return False


def extra_examples(src: Path, already: set[str], tracked: set[str] | None) -> tuple[list[str], str | None]:
    """(names, problem). The top-level examples/*.py files in the checkout that match EXTRA_EXAMPLE_WORDS, are not in
    the fixed list and are tracked at the pinned commit, sorted, at most EXTRA_EXAMPLE_MAX. A match that the pinned
    commit does not have is a problem, never an included file. When git could not say what is tracked (`tracked` is
    None) no extra is taken. A directory that cannot be listed is a problem, not an exception. Nothing is read here."""
    ex = src / "examples"
    try:
        if os.path.islink(ex) or not ex.is_dir():
            return [], None
        entries = [e for e in os.scandir(ex)]
    except OSError as exc:
        return [], f"{ex} cannot be listed: {exc.strerror or exc}"
    names, untracked = [], []
    for entry in entries:
        low = entry.name.lower()
        if (entry.name.endswith(".py") and entry.name not in already and any(w in low for w in EXTRA_EXAMPLE_WORDS)
                and not any(w in low for w in EXTRA_EXAMPLE_SKIP) and _is_file_entry(entry)):
            if tracked is None:
                continue
            (names if f"examples/{entry.name}" in tracked else untracked).append(entry.name)
    if untracked:
        return sorted(names)[:EXTRA_EXAMPLE_MAX], (
            f"{', '.join('examples/' + n for n in sorted(untracked))} is not in the pinned commit; an untracked "
            "example is never given to the coder")
    return sorted(names)[:EXTRA_EXAMPLE_MAX], None



def record(r: dict) -> dict:
    """The part of a reference file that goes in the probe's report: everything except the bytes."""
    out = {k: r[k] for k in ("source", "path", "sha256") if k in r}
    out["name"] = f"reference/{r['name']}"
    out["spec_version"] = r.get("spec_version")
    out["generated"] = bool(r.get("generated"))
    if r.get("generated_from"):
        out["generated_from"] = list(r["generated_from"])
    return out


def report_lines(header: dict) -> list[str]:
    """The report's section on which tt-lang each reference file documents, and a plain sentence on whether the guide
    and the specification agree."""
    refs = [r for r in (header.get("references") or []) if isinstance(r, dict)]
    if not refs:
        return []
    lines = ["## Reference versions", ""]
    ver = {}
    for r in refs:
        name = str(r.get("name", "")).removeprefix("reference/")
        ver[name] = r.get("spec_version")
        v = r.get("spec_version")
        how = f"generated from {', '.join(r.get('generated_from') or [])}; " if r.get("generated") else ""
        lines.append(f"- {name}: {how}from the {r.get('source')}, spec version {v if v else 'unknown'}, "
                     f"sha256 {r.get('sha256')}")
    g, s = ver.get("guide.md"), ver.get("TTLangSpecification.md")
    if g and s and g != s:
        lines += ["", f"The guide documents specification {g} and the specification documents {s}. The coder was taught "
                      "a different version of the language than the simulator runs."]
    elif g and s:
        lines += ["", f"The guide and the specification both document {s}."]
    else:
        lines += ["", "The specification version of the guide or of the specification could not be read, so whether "
                      "they agree is unknown."]
    cons = header.get("ttlang_consistency")
    if isinstance(cons, dict) and isinstance(cons.get("rows"), list):
        lines += ["", "Consistency rows the probe evaluated before it started:"]
        for r in cons["rows"]:
            if isinstance(r, dict):
                lines.append(f"- {r.get('name')}: {r.get('status')}. {r.get('detail')}")
        if cons.get("overridden"):
            lines.append("--allow-stale-skills let a mismatch through: the coder ran on an environment that does not "
                         "match the pin.")
    pin = header.get("ttlang_pin")
    if isinstance(pin, dict):
        lines += ["", f"tt-lang pin: {pin.get('sha')} (simulator {pin.get('sim_version')}, specification "
                      f"{pin.get('spec_version') or 'unknown'}, tt-metal ref {pin.get('tt_metal_ref')})."]
    return lines + [""]
