"""The coder's reference files, taken from the tt-lang the simulator runs.

The kernel probe puts five files in each attempt's reference/ directory: guide.md, examples.md, the specification and
two example kernels. The specification and the examples always come from the tt-lang checkout at the pinned commit
(orchard/ttlang_pin.py). The guide and the examples.md index used to come from the installed tt-lang skill, which
documents an older specification (0.12 against the checkout's 0.20 when this module was written). A coder taught
`ttl.kernel` and then run against a simulator that only knows `ttl.operation` is tested on a language it was not taught.

`assemble` closes that gap:

  * the skill's guide.md and examples.md are shipped only when the specification version the skill documents equals the
    checkout's;
  * when the versions differ, both files are generated from the checkout's own docs (GUIDE_DOCS, EXAMPLES_DOCS), into
    memory, and the probe writes them into the run's own reference directory;
  * when either version cannot be read, the skill's files are kept (nothing says they differ) and the record says the
    version is unknown.

Each file carries its source, sha256, the specification version it documents (None when unknown) and whether it was
generated. Nothing is written into the checkout, the skill directory or the venv. Files are read through
ttlang_env._read_reference, which refuses links, devices and oversized files.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

from orchard import ttlang_env

# The checkout's docs a generated guide.md is made of, in reading order (paths under the checkout).
GUIDE_DOCS = (
    "docs/sphinx/overview.md",
    "docs/sphinx/programming-guide.md",
    "docs/sphinx/simulator-getting-started.md",
    "docs/sphinx/simulator.md",
)
# What a generated examples.md is made of.
EXAMPLES_DOCS = ("docs/EXAMPLES.md", "examples/README.md")
SPEC_REL = "docs/sphinx/specs/TTLangSpecification.md"


def _version_of(path: Path) -> str | None:
    from orchard import skillsfresh
    data = skillsfresh._read_regular(path)
    return skillsfresh.spec_version(data) if data else None


def checkout_spec_version(src_dir) -> str | None:
    """The specification version the tt-lang checkout documents, read from its own TTLangSpecification.md."""
    return _version_of(Path(src_dir) / SPEC_REL)


def skill_spec_version(skill_dir) -> str | None:
    """The specification version the installed tt-lang skill documents."""
    return _version_of(Path(skill_dir) / "TTLangSpecification.md")


def _generate(name: str, docs: tuple[str, ...], env, skill_ver, src_ver, problems: list[str]) -> dict | None:
    """One generated reference file: a header that says what it is, then each source doc under its own marker."""
    src = Path(env.src_dir)
    parts, used = [], []
    for rel in docs:
        data, why = ttlang_env._read_reference(src / rel, src)
        if why:
            problems.append(why)
            continue
        used.append(rel)
        parts.append(f"\n\n<!-- source: {rel} -->\n\n".encode() + data)
    if len(used) != len(docs):
        return None
    head_sha = ttlang_env.head_sha(env) or "an unknown commit"
    header = (f"<!-- generated by tt-orchard from the tt-lang checkout at {head_sha}, which documents specification "
              f"{src_ver}. The installed tt-lang skill documents {skill_ver or 'an unknown version'}, so its {name} is "
              f"not used (skill documents {skill_ver or 'unknown'}). Sources: {', '.join(used)}. -->").encode()
    data = header + b"".join(parts)
    if len(data) > ttlang_env.REFERENCE_MAX_BYTES:
        problems.append(f"the generated {name} is larger than {ttlang_env.REFERENCE_MAX_BYTES // 1024} KiB")
        return None
    return {"name": name, "source": ttlang_env.CHECKOUT_SOURCE, "path": f"generated from {', '.join(used)} in {src}",
            "sha256": hashlib.sha256(data).hexdigest(), "data": data, "spec_version": src_ver, "generated": True,
            "generated_from": used}


def assemble(env, skill_dir) -> tuple[list[dict], list[str]]:
    """(files, problems), in the order of ttlang_env.REFERENCES. Each file is {"name", "source", "path", "sha256",
    "data", "spec_version", "generated"} and, when generated, "generated_from"."""
    skill_dir = Path(skill_dir)
    skill_ver, src_ver = skill_spec_version(skill_dir), checkout_spec_version(env.src_dir)
    use_checkout = bool(skill_ver and src_ver and skill_ver != src_ver)
    roots = {ttlang_env.SKILL_SOURCE: skill_dir, ttlang_env.CHECKOUT_SOURCE: Path(env.src_dir)}
    files, problems = [], []
    generated = {"guide.md": GUIDE_DOCS, "examples.md": EXAMPLES_DOCS}
    for name, source, rel in ttlang_env.REFERENCES:
        if use_checkout and name in generated:
            g = _generate(name, generated[name], env, skill_ver, src_ver, problems)
            if g:
                files.append(g)
            continue
        path = roots[source] / rel
        data, why = ttlang_env._read_reference(path, roots[source])
        if why:
            problems.append(why)
            continue
        files.append({"name": name, "source": source, "path": str(path), "sha256": hashlib.sha256(data).hexdigest(),
                      "data": data, "spec_version": skill_ver if source == ttlang_env.SKILL_SOURCE else src_ver,
                      "generated": False})
    return files, problems


def record(r: dict) -> dict:
    """The part of a reference file that goes in the probe's report: everything except the bytes."""
    out = {k: r[k] for k in ("source", "path", "sha256") if k in r}
    out["name"] = f"reference/{r['name']}"
    out["spec_version"] = r.get("spec_version")
    out["generated"] = bool(r.get("generated"))
    if r.get("generated_from"):
        out["generated_from"] = list(r["generated_from"])
    return out


def report_lines(header: dict) -> list[str]:
    """The report's section on which tt-lang each reference file documents, and a plain sentence on whether the guide
    and the specification agree."""
    refs = [r for r in (header.get("references") or []) if isinstance(r, dict)]
    if not refs:
        return []
    lines = ["## Reference versions", ""]
    ver = {}
    for r in refs:
        name = str(r.get("name", "")).removeprefix("reference/")
        ver[name] = r.get("spec_version")
        v = r.get("spec_version")
        how = f"generated from {', '.join(r.get('generated_from') or [])}; " if r.get("generated") else ""
        lines.append(f"- {name}: {how}from the {r.get('source')}, spec version {v if v else 'unknown'}, "
                     f"sha256 {r.get('sha256')}")
    g, s = ver.get("guide.md"), ver.get("TTLangSpecification.md")
    if g and s and g != s:
        lines += ["", f"The guide documents specification {g} and the specification documents {s}. The coder was taught "
                      "a different version of the language than the simulator runs."]
    elif g and s:
        lines += ["", f"The guide and the specification both document {s}."]
    else:
        lines += ["", "The specification version of the guide or of the specification could not be read, so whether "
                      "they agree is unknown."]
    pin = header.get("ttlang_pin")
    if isinstance(pin, dict):
        lines += ["", f"tt-lang pin: {pin.get('sha')} (simulator {pin.get('sim_version')}, specification "
                      f"{pin.get('spec_version') or 'unknown'}, tt-metal ref {pin.get('tt_metal_ref')})."]
    return lines + [""]
